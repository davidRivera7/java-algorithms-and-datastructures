    private void colocarImagenes() {
        ImageIcon imagen = new ImageIcon("src/imagenes/estrellas.jpg");        
        lblImagenFondo.setIcon(new ImageIcon(imagen.getImage().getScaledInstance( 
                lblImagenFondo.getWidth(), lblImagenFondo.getHeight(), 0)));        
        
        imagen = new ImageIcon("src/imagenes/usuario.png");
        lblImagenUsuario.setIcon(new ImageIcon(imagen.getImage().getScaledInstance(
                lblImagenUsuario.getWidth(), lblImagenUsuario.getHeight(), 0)));                        
    }
    
    private void verificarCampos() {
        if (!txtFieldUsuario.getText().equals(usuario)) {
            JOptionPane.showMessageDialog(null, "Usuario Incorrecto");
            return;
        }
        
        String valorContrasena = "";
        for (char c : passwordConstrasena.getPassword()) {
            valorContrasena += c;
        }
            
        if (!valorContrasena.equals(contrasena)) {
            JOptionPane.showMessageDialog(null, "Contrasena incorrecta");
            return;
        }
        
        JOptionPane.showMessageDialog(null, "Bienvenido " + usuario);                    
    }
    
