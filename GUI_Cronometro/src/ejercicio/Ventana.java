    private void colocarImagenes() {
        ImageIcon imagen = new ImageIcon("src/imagenes/fondo.jpg");
        lblImagenFondo.setIcon(imagen);
        imagen.setImage(imagen.getImage().getScaledInstance(lblImagenFondo.getWidth(),
                lblImagenFondo.getHeight(), 0));
        
        imagen = new ImageIcon("src/imagenes/reloj.png");
        lblImagenReloj.setIcon(imagen);
        imagen.setImage(imagen.getImage().getScaledInstance(lblImagenReloj.getWidth(),
                lblImagenReloj.getHeight(), 0));
    }        

    private Timer obtenerTimer() {
        
        return new Timer(10, new ActionListener() {
            
            private int centesimas;
            private int segundos;
            private int minutos;
            private int horas;            
            
            @Override
            public void actionPerformed(ActionEvent e) {
                centesimas++;
                
                if (centesimas == 100) {
                    segundos++;
                    centesimas = 0;
                }
                
                if (segundos == 60) {
                    minutos++;
                    segundos = 0;
                }
                
                if (minutos == 60) {
                    horas++;
                    minutos = 0;
                }
                
                actualizarLblTiempo();
            }
            
            private void actualizarLblTiempo() {
                lblTiempo.setText(
                        ((horas < 10) ? "0" : "") + horas + " : " + 
                        ((minutos < 10) ? "0" : "") + minutos + " : " + 
                        ((segundos < 10) ? "0" : "") + segundos + " : " + 
                        ((centesimas < 10) ? "0" : "") + centesimas
                );
            }
        });
        
    }
        
